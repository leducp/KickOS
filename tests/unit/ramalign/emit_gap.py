# Seeded block sequences and the offsets the composition tool's ArenaModel places them at, for
# the allocator's copy to be checked against:
#
#   emit_gap.py <scratch directory> <table.h>

import random
import sys

from kickos_compose.region import ArenaModel

SEQUENCES = 64
BLOCKS = 28
# (size, alignment) pools: a pow2 unit names a region by its rounded size, a granule unit
# aligns on the granule.
POW2 = [(16, 16), (32, 32), (64, 64), (512, 512), (1024, 1024), (4096, 4096), (8192, 8192)]
GRANULE = [(32, 32), (96, 32), (160, 32), (4096, 32), (544, 32), (8192, 32), (1056, 32)]


def main(argv):
    table = argv[2]
    rng = random.Random(0x6A9)
    out = []
    for n in range(SEQUENCES):
        pool = POW2
        if n % 2:
            pool = GRANULE
        model = ArenaModel(0)
        steps = []
        for _ in range(BLOCKS):
            size, align = rng.choice(pool)
            steps.append("{%du, %du, %du}" % (size, align, model.place(size, align)))
        out.append("    {{%s}}," % ", ".join(steps))
    with open(table, "w") as f:
        f.write("// Generated by tests/unit/ramalign/emit_gap.py.\n")
        f.write("#include <stddef.h>\n\n#define GAP_BLOCKS %d\n\n" % BLOCKS)
        f.write("struct GapStep\n{\n    size_t size;\n    size_t align;\n    size_t offset;\n};\n\n")
        f.write("struct GapSequence\n{\n    GapStep steps[GAP_BLOCKS];\n};\n\n")
        f.write("static GapSequence const GAP_SEQUENCES[] = {\n%s\n};\n" % "\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
