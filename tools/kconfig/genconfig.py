# Resolves the Kconfig tree and writes what the build reads.
#
#   in :  Kconfig tree + a BASE (the live .config if there is one, else the board's
#         defconfig) + CONFIG_x=y overrides
#   out:  <gen>/.config                            the resolved configuration
#         <gen>/include/kickos/board_config.h       the C-visible knobs
#         <gen>/kickos_config.cmake                 the build-graph facts
#         <gen>/amp-peer-seed.cmake                 an own-image AMP node's, what its peers are
#                                                   configured from
#
# Running kconfiglib is not by itself the scheme: kconfiglib WARNS and falls back on
# a symbol's default for an out-of-range int, and drops an assignment whose
# dependencies are unmet. check_assignments reads every requested value back and
# refuses a mismatch, so a board asking for what it cannot have fails here instead
# of building with a value nobody chose.

import hashlib
import os
import re
import sys

import kconfiglib

# Which knobs cross either boundary is a RULE, not a list: every symbol named KICKOS_*, in
# declaration order. The names are the ones the tree uses, not CONFIG_-prefixed.
#
# The HEADER takes the numeric ones and the bools, a bool as 0 or 1 whether or not its
# dependencies are met, so C reads every one with `#if` and never with `#if defined`.
KNOB_PREFIX = "KICKOS_"
C_KNOB_TYPES = (kconfiglib.INT, kconfiglib.HEX)

# CMake's own false constants, matching `if(<variable>)`: anything else is true, an arbitrary
# word included. This is how a candidate's value becomes y or n for a bool symbol.
CMAKE_FALSE = ("", "0", "OFF", "NO", "FALSE", "N", "IGNORE", "NOTFOUND")


def sym_int(kconf, name):
    sym = kconf.syms.get(name)
    if sym is None:
        return None
    value = sym.str_value
    if value == "":
        return None
    return int(value, 0)


def sym_str(kconf, name):
    sym = kconf.syms.get(name)
    if sym is None:
        return ""
    return sym.str_value


def sym_help(sym):
    for node in sym.nodes:
        if node.help:
            return "\n    " + node.help.replace("\n", "\n    ")
    return ""


def write_board_config(path, kconf):
    lines = [
        "/* SPDX-License-Identifier: CECILL-C */",
        "/* GENERATED by tools/kconfig/genconfig.py. Edits are overwritten. */",
        "/* Pure integer macros only: also included from startup.S. */",
        "",
        "#ifndef KICKOS_BOARD_CONFIG_H",
        "#define KICKOS_BOARD_CONFIG_H",
        "",
    ]
    # #ifndef and not a bare #define: a knob an application reads also arrives as a -D of the
    # same value, and a host test's posture as a -D of another, either of which a bare
    # #define would turn into a -Werror redefinition.
    for sym in kconf.unique_defined_syms:
        if not sym.name.startswith(KNOB_PREFIX):
            continue
        if sym.type == kconfiglib.BOOL:
            value = "0"
            if sym.str_value == "y":
                value = "1"
        elif sym.type in C_KNOB_TYPES:
            # Empty when the symbol's dependencies are unmet, so it is not offered on this
            # board and C keeps its own default.
            if sym.str_value == "":
                continue
            # str_value, not an int: it already carries the declared form, so a hex knob
            # stays hexadecimal and reads like the register address it is.
            value = sym.str_value
        else:
            continue
        lines.append("#ifndef " + sym.name)
        lines.append("#define " + sym.name + " " + value)
        lines.append("#endif")
    lines.append("")
    lines.append("#endif /* KICKOS_BOARD_CONFIG_H */")
    with open(path, "w") as handle:
        handle.write("\n".join(lines) + "\n")


def cmake_escape(value):
    # A quoted set() argument still expands ${...}/$ENV{...}, still ends on an
    # unescaped quote, and still splits on an unescaped semicolon (CMake has no
    # string type distinct from a list), so all three need a backslash, and the
    # backslash itself must be escaped first or it can eat the character after it.
    value = value.replace("\\", "\\\\")
    value = value.replace('"', '\\"')
    value = value.replace("$", "\\$")
    value = value.replace(";", "\\;")
    return value


def cmake_knob(sym):
    if sym.type == kconfiglib.STRING:
        return '"' + cmake_escape(sym.str_value) + '"'
    if sym.type in C_KNOB_TYPES:
        # Empty when the dependencies are unmet, and CMake has no #ifndef fallback for it
        # the way the header has: an unset variable and an empty one read alike in if(),
        # math() refuses an empty expression, and add_compile_definitions(X=${X}) would
        # emit a bare `X=` that satisfies #if defined at every site. Zero is what every
        # reader here already spells "not on this board".
        if sym.str_value == "":
            return "0"
        # Decimal even for a hex knob, so a value CMake compares with EQUAL or feeds to
        # math() carries no base prefix.
        return str(int(sym.str_value, 0))
    if sym.str_value == "y":
        return "ON"
    return "OFF"


def prompted(sym):
    for node in sym.nodes:
        if node.prompt:
            return True
    return False


def write_cmake_fragment(path, kconf, sources, base, derived=()):
    lines = ["# GENERATED by tools/kconfig/genconfig.py. Edits are overwritten.",
             # Which file this resolution was based on: a live .config outranks the
             # defconfig, so an in-place defconfig edit does not reach an existing build.
             'set(KICKOS_KCONFIG_BASE "' + cmake_escape(base) + '")']
    for sym in kconf.unique_defined_syms:
        if sym.name.startswith(KNOB_PREFIX):
            lines.append("set(" + sym.name + " " + cmake_knob(sym) + ")")
    for name, value in derived:
        if isinstance(value, int):
            lines.append("set(" + name + " " + str(value) + ")")
        else:
            lines.append("set(" + name + ' "' + cmake_escape(value) + '")')
    # Every declaration file that was read, absolute. CMake re-runs configure when one
    # changes and takes the list from here, so it never learns which Kconfig files
    # exist. The override fragment is excluded: it lives in the build tree and is
    # rewritten every configure.
    inputs = []
    for name in list(kconf.kconfig_filenames) + list(sources):
        inputs.append(cmake_escape(os.path.abspath(name)))
    lines.append('set(KICKOS_KCONFIG_SOURCES "' + ";".join(inputs) + '")')
    with open(path, "w") as handle:
        handle.write("\n".join(lines) + "\n")


def amp_geometry(kconf):
    """The refusal of an own-image partition's geometry, or None."""
    for name in ("KICKOS_AMP_PARTITION_BASE", "KICKOS_AMP_NODE_SHARE", "KICKOS_AMP_SHARED_SIZE"):
        if sym_int(kconf, name) == 0:
            return (name + " is unstated. Every node's image is linked at "
                    "KICKOS_AMP_PARTITION_BASE plus its own index times KICKOS_AMP_NODE_SHARE, "
                    "and the region every node writes sits above the last of them, "
                    "KICKOS_AMP_SHARED_SIZE wide: with any of the three unstated the images link "
                    "on top of each other.")
    no_base = sym_int(kconf, "KICKOS_AMP_TEXT_BASE") == 0
    no_share = sym_int(kconf, "KICKOS_AMP_TEXT_SHARE") == 0
    if no_base != no_share:
        return ("KICKOS_AMP_TEXT_BASE and KICKOS_AMP_TEXT_SHARE describe one aperture, the "
                "separate span a part executing in place keeps its text in, a node's text "
                "linked at that base plus its own index times that stride. State both, or "
                "neither where the part has one span and KICKOS_AMP_PARTITION_BASE describes "
                "all of it.")
    return None


def amp_cores(kconf, nodes):
    """(map, refusal) of an own-image node: the core each node runs on, in node order."""
    stated = sym_str(kconf, "KICKOS_AMP_NODE_CORES")
    cores = []
    if stated != "":
        cores = stated.split(",")
    what = "KICKOS_AMP_NODE_CORES='" + stated + "'"
    if len(cores) != nodes:
        return None, (what + ": it names " + str(len(cores)) + " core(s) for a partition of "
                      + str(nodes) + " node(s). It states, per node and in node order, which "
                      "machine core carries that node, and amp::ring takes its doorbell target "
                      "from it. Give one core per node.")
    span = sym_int(kconf, "KICKOS_AMP_PARTITION_CORES")
    seen = []
    for node, core in enumerate(cores):
        if re.fullmatch(r"[0-9]+", core) is None:
            return None, what + ": entry '" + core + "' is not a core index."
        if int(core) >= span:
            return None, (what + ": node " + str(node) + " is on core " + core + " and the "
                          "partition spans " + str(span) + " core(s). The doorbell's cells "
                          "are indexed by core, so this node would answer out of the matrix.")
        if int(core) in seen:
            return None, (what + ": two nodes are on core " + str(int(core)) + ". Each node's "
                          "image drives its own core, and the doorbell's rendezvous row is "
                          "written by that core alone.")
        seen.append(int(core))
    if seen[0] != 0:
        return None, (what + ": node 0 is on core " + cores[0] + ". Node 0 is the partition "
                      "primary and runs on the core the machine resets into, core 0, so a peer "
                      "mapped onto core 0 is the primary releasing itself and the boot dies in "
                      "the launch handshake. Give node 0 core 0 and permute the peers instead.")
    return cores, None


def amp_ports(kconf, nodes, self_node):
    """([(node, port)], refusal) of KICKOS_AMP_PORTS, in list order: an entry's position is its
    capability index."""
    stated = sym_str(kconf, "KICKOS_AMP_PORTS")
    what = "KICKOS_AMP_PORTS='" + stated + "'"
    if stated == "":
        return None, (what + ": this board is a node of an AMP partition and the list names no "
                      "crossing. A node no port capability reaches can neither be called nor "
                      "call. State the whole partition's ports once, as node:port pairs in node "
                      "order, for example \"0:2,1:3\" for a node 0 serving port 2 and a node 1 "
                      "serving port 3.")
    pairs = []
    for entry in stated.split(","):
        match = re.fullmatch(r"([0-9]+):([0-9]+)", entry)
        if match is None:
            return None, (what + ": entry '" + entry + "' is not a node:port pair. The list "
                          "names, for the whole partition, which node serves which port.")
        node, port = int(match.group(1)), int(match.group(2))
        if node >= nodes:
            return None, (what + ": entry '" + entry + "' names node " + str(node) + " and the "
                          "partition holds " + str(nodes) + " node(s).")
        if port == 1:
            return None, (what + ": entry '" + entry + "' names port 1, which every reply "
                          "travels on, routed to the caller its token names, so no node can "
                          "serve it. Service ports start at 2.")
        if port == 0 and node == self_node:
            return None, (what + ": entry '" + entry + "' names port 0 for this image's own "
                          "node. Port 0 is the echo the window layer answers with no thread, "
                          "and a node that runs a kernel binds every port named for it, taking "
                          "the echo from the window layer. Name port 0 only for a peer that runs "
                          "no kernel.")
        if port >= 32:
            return None, (what + ": entry '" + entry + "' names port " + str(port) + " and a "
                          "node's mint is a 32-bit mask, so 31 is its last port.")
        if (node, port) in pairs:
            return None, (what + ": node " + str(node) + " port " + str(port) + " is named "
                          "twice, which would seat two capabilities for one endpoint and shift "
                          "every index after it.")
        pairs.append((node, port))
    slots = sym_int(kconf, "KICKOS_MAX_ENDPOINTS")
    if slots <= len(pairs):
        return None, (what + ": it names " + str(len(pairs)) + " crossing(s) and the board "
                      "provisions " + str(slots) + " endpoint slot(s). Each entry holds one for "
                      "the life of the image, so the partition cannot seat itself and leave the "
                      "app any. Raise CONFIG_KICKOS_MAX_ENDPOINTS.")
    return pairs, None


def amp_partition(kconf):
    """(derived facts, refusal): what the build reads of the AMP partition, as [(name, value)],
    the defaults of an image that is no node included."""
    if sym_int(kconf, "KICKOS_AMP_NODE") != 1:
        return [("KICKOS_AMP_SELF_NODE", 0), ("KICKOS_AMP_PORT_COUNT", 0),
                ("KICKOS_AMP_PORT_LOCAL", 0), ("KICKOS_AMP_PORT_NODE_INIT", ""),
                ("KICKOS_AMP_PORT_PORT_INIT", "")], None
    nodes = sym_int(kconf, "KICKOS_AMP_NODES")
    owner = sym_int(kconf, "KICKOS_AMP_RESET_OWNER")
    if owner >= nodes:
        return None, ("KICKOS_AMP_RESET_OWNER=" + str(owner) + ": the partition holds "
                      + str(nodes) + " node(s), numbered from 0.")
    facts = []
    self_node = 0
    if sym_int(kconf, "KICKOS_AMP_OWN_IMAGE") == 1:
        refusal = amp_geometry(kconf)
        if refusal is not None:
            return None, refusal
        self_node = sym_int(kconf, "KICKOS_AMP_NODE_ID")
        if self_node >= nodes:
            return None, ("KICKOS_AMP_NODE_ID=" + str(self_node) + ": the partition holds "
                          + str(nodes) + " node(s), numbered from 0.")
        cores, refusal = amp_cores(kconf, nodes)
        if refusal is not None:
            return None, refusal
        facts.append(("KICKOS_AMP_SELF_CORE", int(cores[self_node])))
    pairs, refusal = amp_ports(kconf, nodes, self_node)
    if refusal is not None:
        return None, refusal
    local = len([node for node, port in pairs if node == self_node])
    facts.extend([("KICKOS_AMP_SELF_NODE", self_node), ("KICKOS_AMP_PORT_COUNT", len(pairs)),
                  ("KICKOS_AMP_PORT_LOCAL", local),
                  ("KICKOS_AMP_PORT_NODE_INIT", ",".join(str(node) for node, port in pairs)),
                  ("KICKOS_AMP_PORT_PORT_INIT", ",".join(str(port) for node, port in pairs))])
    return facts, None


def amp_fingerprint(config):
    """The two 32-bit words over a resolved .config with the one per-node symbol taken out: a
    32-bit linker truncates one 64-bit --defsym without saying so."""
    with open(config, encoding="utf-8") as handle:
        lines = [line.rstrip("\n") for line in handle if re.match(r"CONFIG_[A-Z0-9_]+=", line)]
    common = re.sub(r"CONFIG_KICKOS_AMP_NODE_ID=[0-9]+", "", ";".join(lines))
    digest = hashlib.sha256(common.encode("utf-8")).hexdigest()
    return digest[0:8], digest[8:16]


def resolved_value(sym):
    """The value a .config states for `sym`, its quotes taken off, or None where it states none."""
    line = sym.config_string
    prefix = "CONFIG_" + sym.name + "="
    if not line.startswith(prefix):
        return None
    value = line[len(prefix):].rstrip("\n")
    if len(value) >= 2 and value.startswith('"') and value.endswith('"'):
        value = value[1:-1]
    return value


def write_amp_seed(path, kconf, by_build):
    """What a peer of this own-image node is configured from beside node 0's cache entries: every
    knob a -D can move, as this node resolved it, but the board and the node index, which
    build-partition.sh names to each peer, and the knobs each node's build requests itself."""
    skip = set(by_build) | {"KICKOS_BOARD", "KICKOS_AMP_NODE_ID"}
    values = []
    flags = []
    for sym in kconf.unique_defined_syms:
        if not sym.name.startswith(KNOB_PREFIX) or sym.name in skip:
            continue
        if prompted(sym) and sym.choice is None:
            if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
                flags.append(sym)
            else:
                values.append(sym)
    # A promptless string a -D reaches through its choice's member.
    for sym in kconf.unique_defined_syms:
        if sym.name.startswith(KNOB_PREFIX) and sym.name not in skip and choice_values(kconf, sym):
            values.append(sym)
    lines = ["# Written by node " + sym_str(kconf, "KICKOS_AMP_NODE_ID")
             + "'s configure. Read by tools/amp/build-partition.sh."]
    for sym in values:
        value = resolved_value(sym)
        if value is not None:
            lines.append("set(" + sym.name + ' "' + value + '" CACHE STRING "" FORCE)')
    # An off bool is a comment in a .config, not `=n`, so it is seeded OFF rather than left
    # unstated for the peer's own default.
    for sym in flags:
        flag = "OFF"
        if resolved_value(sym) == "y":
            flag = "ON"
        lines.append("set(" + sym.name + " " + flag + ' CACHE BOOL "" FORCE)')
    write_if_changed(path, "\n".join(lines) + "\n")


def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path) as handle:
            if handle.read() == text:
                return
    with open(path, "w") as handle:
        handle.write(text)


def requested_assignments(paths):
    wanted = []
    for path in paths:
        with open(path) as handle:
            for line in handle:
                line = line.strip()
                if not line.startswith("CONFIG_"):
                    continue
                if "=" not in line:
                    continue
                name, value = line[len("CONFIG_"):].split("=", 1)
                wanted.append((name, value))
    return wanted


# For a promptless string whose every default is a constant under a member of one choice, or
# under no condition, the member each value selects, keyed in lower case; empty for any other
# symbol. The unconditional value selects the one member no other default names.
def choice_values(kconf, sym):
    if sym is None or sym.type != kconfiglib.STRING or prompted(sym):
        return {}
    members = {}
    bare = []
    choice = None
    for default, cond in sym.defaults:
        if not default.is_constant:
            return {}
        if cond is kconf.y:
            bare.append(default.name)
            continue
        if not isinstance(cond, kconfiglib.Symbol) or cond.choice is None:
            return {}
        if choice is not None and cond.choice is not choice:
            return {}
        choice = cond.choice
        members[default.name.lower()] = cond.name
    if choice is None:
        return {}
    rest = [member.name for member in choice.syms if member.name not in members.values()]
    if len(bare) == 1 and len(rest) == 1:
        members[bare[0].lower()] = rest[0]
    return members


def candidate_request(kconf, name, value):
    # One of the two is empty: a CONFIG_ line the loader can take, or why no request could
    # be built from this name.
    sym = kconf.syms.get(name)
    if sym is None:
        return ("", "no such symbol")
    if not prompted(sym):
        members = choice_values(kconf, sym)
        if not members:
            return ("", "no prompt, so nothing can set it: it is derived, not configuration")
        if value.lower() not in members:
            return ("", "not one of " + ", ".join(sorted(members)))
        return ("CONFIG_" + members[value.lower()] + "=y", "")
    if sym.choice is not None:
        return ("", "a member of a choice: a variant defconfig selects one, and no -D of a "
                    "member's own name reaches it")
    if sym.type == kconfiglib.STRING:
        # kconfiglib's own quoting, which cares about a backslash and a quote and nothing
        # else. check_assignments strips the quotes back off to compare.
        quoted = value.replace("\\", "\\\\").replace('"', '\\"')
        return ("CONFIG_" + name + '="' + quoted + '"', "")
    if sym.type in C_KNOB_TYPES:
        return ("CONFIG_" + name + "=" + value, "")
    # BOTH DIRECTIONS: a candidate resolved off must travel as `n`, or a defconfig that
    # enables something outranks a command line asking to turn it off.
    flag = "y"
    upper = value.upper()
    if upper in CMAKE_FALSE or upper.endswith("-NOTFOUND"):
        flag = "n"
    return ("CONFIG_" + name + "=" + flag, "")


def unstated_fallbacks(kconf):
    # A visible choice no request states resolves to its first VISIBLE member when its declared
    # default is unavailable, which is a silent change of meaning; refuse it instead.
    refused = []
    for choice in kconf.unique_choices:
        if choice.visibility == 0 or choice.user_selection is not None:
            continue
        default = None
        for sym, cond in choice.defaults:
            if kconfiglib.expr_value(cond):
                default = sym
                break
        if default is None or default.visibility != 0:
            continue
        members = [sym.name for sym in choice.syms if sym.visibility != 0]
        prompt = choice.nodes[0].prompt[0]
        refused.append("REFUSED the choice \"" + prompt + "\": its default " + default.name
                       + " is unavailable (unmet dependency: "
                       + kconfiglib.expr_str(default.direct_dep) + "), and nothing states a "
                       + "member, so it would resolve to " + choice.selection.name
                       + ". State one of " + ", ".join(members) + "." + sym_help(default))
    return refused


def check_assignments(kconf, wanted):
    # Only the LAST assignment of each symbol is checked: a later fragment REPLACES
    # an earlier one, and a choice member requested later turning an earlier one off is the
    # mechanism working rather than a conflict. The later one is still checked.
    last = {}
    displaced = set()
    for name, value in wanted:
        last[name] = value
        sym = kconf.syms.get(name)
        if sym is None or sym.choice is None or value != "y":
            continue
        displaced.discard(name)
        for sibling in sym.choice.syms:
            if sibling.name != name:
                displaced.add(sibling.name)

    refused = []
    for name in sorted(last):
        value = last[name]
        if name in displaced:
            continue
        sym = kconf.syms.get(name)
        if sym is None:
            refused.append((name, value, "no such symbol"))
            continue
        got = sym.str_value
        if got == value.strip('"'):
            continue
        if not prompted(sym):
            # kconfiglib drops a user value on a promptless symbol and says nothing, so
            # without this arm the refusal below would blame the symbol's dependency,
            # which for every promptless symbol in this tree is `y`.
            reason = ("no prompt, so nothing can set it: it is derived, not "
                      "configuration")
        elif sym.type in (kconfiglib.INT, kconfiglib.HEX) and sym.ranges:
            low, high, _cond = sym.ranges[0]
            reason = ("outside the declared range [" + low.str_value + ", " +
                      high.str_value + "]")
        else:
            reason = "unmet dependency: " + kconfiglib.expr_str(sym.direct_dep)
        reason = reason + ": resolved to '" + got + "'"
        # The declaration's own help, so a refusal explains itself instead of leaving a
        # hand-written hint to be maintained somewhere else and go stale.
        reason = reason + sym_help(sym)
        refused.append((name, value, reason))
    return refused


def main(argv):
    if len(argv) < 4:
        sys.stderr.write("usage: genconfig.py <srcdir> <defconfig> <gendir> "
                         "[CONFIG_X=y | offer:X=v | assert:X=v ...]\n")
        return 2
    srcdir, defconfig, gendir = argv[1], argv[2], argv[3]
    requests = argv[4:]

    defconfig = os.path.abspath(defconfig)
    gendir = os.path.abspath(gendir)
    os.chdir(srcdir)

    # Two ROLES, not two homes for one value. The defconfig is the saved, reviewable,
    # git-stored starting point; <gen>/.config is the LIVE state this build is based on.
    # So the defconfig seeds the first configure and .config is authoritative after
    # that, exactly as a preset's cacheVariables seed CMakeCache.txt once and the cache
    # rules afterwards. Editing a defconfig therefore does NOT reach an existing build
    # dir until it is reloaded, which is the same contract CMake already has.
    live = os.path.join(gendir, ".config")
    stamp = os.path.join(gendir, ".defconfig")
    base = defconfig
    if os.path.exists(live):
        base = live
        # Which defconfig the live state came from. Selecting another variant in an
        # EXISTING build directory would otherwise be dropped in silence: the live
        # .config is the base, so the newly named defconfig is never read, and board,
        # arch, family and chip all still agree so no other check notices. Refusing is
        # the answer rather than reloading, because reloading discards whatever
        # menuconfig has accumulated here.
        previous = ""
        if os.path.exists(stamp):
            previous = open(stamp).read().strip()
        if previous != "" and previous != defconfig:
            sys.stderr.write(
                "REFUSED variant change: this build directory is configured from\n"
                "  " + previous + "\nand the request names\n  " + defconfig + "\n"
                "The live " + live + " is the state this build is based on, so the new "
                "defconfig would be read by nothing. Use a fresh build directory, or "
                "delete that .config to reload from the new variant.\n")
            return 1
    kconf = kconfiglib.Kconfig("Kconfig", warn_to_stderr=True)

    # THREE REQUEST SHAPES, and only the first is stated in Kconfig's own syntax:
    #
    #   CONFIG_<name>=<value>   a request, honoured or refused as written
    #   offer:<NAME>=<value>    a CMake variable whose name MIGHT be a knob
    #   assert:<NAME>=<value>   the same, and only a command line or a preset can have
    #                           made it: it is an UNINITIALIZED cache entry, so no
    #                           declaration in the build owns the name
    #
    # CMake cannot tell a knob from its own variables, the KICKOS_* space also carrying the
    # board identity, the build-graph switches and the per-board link knobs, so it offers
    # every one of them and the declarations decide here. A promptless string whose value
    # names a choice member is requested as that member. Any other offer the declarations
    # cannot take is DROPPED, so a promptless symbol stays unreachable by any -D. An ASSERTED
    # one naming a symbol no request can reach is refused instead, since nothing but the
    # request itself put that name there.
    overrides = []
    by_build = []
    for request in requests:
        # The shape FIRST, and a nameless one is refused rather than dropped: a request the
        # loader and the read-back check both skip would otherwise look honoured.
        shape = ""
        for prefix in ("CONFIG_", "offer:", "assert:"):
            if request.startswith(prefix) and "=" in request:
                shape = prefix
        name = ""
        value = ""
        if shape != "":
            name, value = request[len(shape):].split("=", 1)
        if name == "":
            sys.stderr.write("REFUSED request '" + request + "': not of the form "
                             "CONFIG_<name>=<value>, offer:<NAME>=<value> or "
                             "assert:<NAME>=<value>\n")
            return 1
        if shape == "CONFIG_":
            # Only the build itself spells a request this way, so each node makes it alike.
            overrides.append(request)
            by_build.append(name)
            continue
        built, why = candidate_request(kconf, name, value)
        if built != "":
            overrides.append(built)
            continue
        if shape == "offer:" and not choice_values(kconf, kconf.syms.get(name)):
            continue
        if why == "no such symbol":
            # The KICKOS_ namespace is wider than Kconfig: a build-graph switch or a
            # per-board link knob is declared in CMake alone and appears in no .config.
            # Dropping it here leaves CMake's own "manually-specified variables were not
            # used" notice to report a name that is neither.
            continue
        sys.stderr.write("REFUSED -D" + name + "=" + value + ": " + why + "\n")
        return 1

    print(kconf.load_config(base))

    # Every symbol the loaded BASE named that the tree does not declare; the override
    # fragment is loaded further down, so nothing here came from a -D. kconfiglib does not
    # warn on one by default (warn_assign_undef is off), and a hand-edited live .config is
    # not read back as a set of requests, so a typo there would otherwise land nowhere at
    # all and say nothing.
    if kconf.missing_syms:
        for name, value in kconf.missing_syms:
            sys.stderr.write("REFUSED CONFIG_" + name + "=" + value
                             + ": no such symbol\n")
        # ONLY where the base was the live state: a defconfig naming a symbol the tree does
        # not declare is an edit to fix, while a .config carrying one is a directory the tree
        # moved past.
        if base != defconfig:
            sys.stderr.write(
                "The live " + live + " is the state this build is based on, and the tree "
                "no longer declares that symbol. Use a fresh build directory, or delete "
                "that .config to reload from " + defconfig + ".\n")
        return 1

    # Only the DEFCONFIG's lines are read back as requests. A live .config is state, not
    # a set of requests: every symbol in it is an explicit value, so checking them would
    # report the resolution disagreeing with itself.
    sources = []
    if base == defconfig:
        sources.append(defconfig)
    if overrides:
        # The loader keeps the LAST assignment of a symbol, so a name given twice makes
        # which request is honoured depend on argument order. The warning that would say so
        # is turned off below; this replaces it.
        seen = {}
        for override in overrides:
            name = override[len("CONFIG_"):].split("=", 1)[0]
            if name in seen:
                sys.stderr.write("REFUSED override '" + override + "': CONFIG_" + name
                                 + " is requested twice, already as '" + seen[name]
                                 + "'\n")
                return 1
            seen[name] = override
        os.makedirs(gendir, exist_ok=True)
        fragment = os.path.join(gendir, "override.config")
        with open(fragment, "w") as handle:
            handle.write("\n".join(overrides) + "\n")
        # After the first configure the base is the live .config, in which every forwarded
        # knob carries an explicit value, so a request repeating that value is redundant
        # rather than a finding. CMakeLists escalates any warning from here to a CMake
        # WARNING, which would put a spurious one on every re-configure. A request naming a
        # DIFFERENT value still warns.
        kconf.warn_assign_redun = False
        try:
            print(kconf.load_config(fragment, replace=False))
        finally:
            kconf.warn_assign_redun = True
        sources.append(fragment)

    refused = check_assignments(kconf, requested_assignments(sources))
    if refused:
        for name, value, reason in refused:
            sys.stderr.write("REFUSED CONFIG_" + name + "=" + value + ": " +
                             reason + "\n")
        return 1
    fallbacks = unstated_fallbacks(kconf)
    if fallbacks:
        sys.stderr.write("\n".join(fallbacks) + "\n")
        return 1
    amp, refusal = amp_partition(kconf)
    if refusal is not None:
        sys.stderr.write("REFUSED " + refusal + "\n")
        return 1

    os.makedirs(os.path.join(gendir, "include", "kickos"), exist_ok=True)
    kconf.write_config(os.path.join(gendir, ".config"))
    with open(stamp, "w") as handle:
        handle.write(defconfig + "\n")
    seed = os.path.join(gendir, "amp-peer-seed.cmake")
    if sym_int(kconf, "KICKOS_AMP_NODE") == 1 and sym_int(kconf, "KICKOS_AMP_OWN_IMAGE") == 1:
        high, low = amp_fingerprint(os.path.join(gendir, ".config"))
        amp.extend([("KICKOS_AMP_CONFIG_FP_HI", high), ("KICKOS_AMP_CONFIG_FP_LO", low)])
        write_amp_seed(seed, kconf, by_build)
    elif os.path.exists(seed):
        os.remove(seed)
    write_board_config(
        os.path.join(gendir, "include", "kickos", "board_config.h"), kconf)
    write_cmake_fragment(os.path.join(gendir, "kickos_config.cmake"), kconf,
                         [defconfig], base, amp)

    print("board=" + sym_str(kconf, "KICKOS_BOARD") +
          " arch=" + sym_str(kconf, "KICKOS_ARCH") +
          " chip=" + sym_str(kconf, "KICKOS_CHIP") +
          " mpu=" + str(sym_int(kconf, "KICKOS_HAVE_MPU")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
